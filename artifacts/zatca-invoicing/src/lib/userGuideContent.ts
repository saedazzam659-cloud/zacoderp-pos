export function getUserGuideChapters(user: any): GuideChapter[] {
  const rawPermissions = user?.company?.menuPermissions;
  const enabledGroups = [...MODULE_GROUPS, SIMPLE_MANUFACTURING_GUIDE_GROUP].filter((group) =>
    group.key !== "demoAnalytics"
      && group.moduleKeys.some((key) => companyAllowsMenuModuleKey(rawPermissions, key)),
  );

  const moduleChapters = enabledGroups.map((group): GuideChapter => {
    const copy = GUIDE_COPY[group.key] ?? genericCopy(group);
    return {
      ...copy,
      id: group.key,
      title: group.label,
      screens: group.screens.filter((screen) => companyAllowsScreen(user, screen.path)),
      ...(group.key === "simple_manufacturing"
        ? {
            screenshot: {
              src: "/user-guide/screenshots/simple-manufacturing.png",
              alt: "لقطة فعلية لسجل أوامر التصنيع المبسط في زاكود ERP",
              caption: "لقطة من بيئة معاينة ببيانات اختبار، وتعرض حالة السجل عندما لا توجد أوامر تصنيع بعد.",
            },
          }
        : {}),
    };
  });

  return [GENERAL_CHAPTER, ...moduleChapters];
}