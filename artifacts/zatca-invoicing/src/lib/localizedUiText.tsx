export function localizeUiTextForLanguage(value: string, language: string): string {
  if (!language?.toLowerCase().startsWith("en")) return value;
  const trimmed = value.trim();
  const translated = translations.get(trimmed);
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

/**
 * Translate static labels in generated print HTML without rewriting record
 * values. Exact text values found in the source document data are protected.
 */
export function localizePrintHtml(html: string, language: string, documentData?: unknown): string {
  if (!language?.toLowerCase().startsWith("en") || typeof DOMParser === "undefined") return html;

  const protectedValues = new Set<string>();
  const englishRecordNames = new Map<string, string>();
  const ambiguousRecordNames = new Set<string>();
  const visited = new WeakSet<object>();
  const addEnglishName = (arabic: unknown, english: unknown) => {
    if (typeof arabic !== "string" || typeof english !== "string") return;
    const key = arabic.trim().toLowerCase();
    const value = english.trim();
    if (!key || !value) return;
    const previous = englishRecordNames.get(key);
    if (previous && previous !== value) {
      englishRecordNames.delete(key);
      ambiguousRecordNames.add(key);
      return;
    }
    if (!ambiguousRecordNames.has(key)) englishRecordNames.set(key, value);
  };
  const collectValues = (value: unknown) => {
    if (typeof value === "string") {
      const normalized = value.trim();
      if (normalized) protectedValues.add(normalized);
      return;
    }
    if (typeof value === "number" && Number.isFinite(value)) {
      protectedValues.add(String(value));
      return;
    }
    if (!value || typeof value !== "object") return;
    if (visited.has(value)) return;
    visited.add(value);
    if (value instanceof Map) {
      for (const [key, item] of value) {
        if (typeof key === "string" && /[\u0600-\u06ff]/.test(key)) addEnglishName(key, item);
        collectValues(key);
        collectValues(item);
      }
      return;
    }
    if (value instanceof Set) {
      for (const item of value) collectValues(item);
      return;
    }
    const record = value as Record<string, unknown>;
    for (const [key, item] of Object.entries(record)) {
      if (key.endsWith("Ar")) addEnglishName(item, record[`${key.slice(0, -2)}En`]);
    }
    for (const item of Object.values(value)) collectValues(item);
  };
  collectValues(documentData);

  const doc = new DOMParser().parseFromString(html, "text/html");
  doc.documentElement.lang = "en";
  doc.documentElement.dir = "ltr";
  for (const node of Array.from(doc.querySelectorAll('[dir="rtl"]'))) {
    node.setAttribute("dir", "ltr");
  }

  const walker = doc.createTreeWalker(doc.body, 4);
  const translateStaticFragments = (value: string): string => {
    if (!/[\u0600-\u06ff]/.test(value)) return value;
    const protectedRanges: Array<[number, number]> = [];
    for (const protectedValue of protectedValues) {
      if (protectedValue.length < 2) continue;
      let position = value.indexOf(protectedValue);
      while (position >= 0) {
        protectedRanges.push([position, position + protectedValue.length]);
        position = value.indexOf(protectedValue, position + protectedValue.length);
      }
    }
    const bilingualSeparator = value.indexOf(" — ");
    if (bilingualSeparator >= 0) {
      const left = value.slice(0, bilingualSeparator);
      const right = value.slice(bilingualSeparator + 3);
      if (
        /[\u0600-\u06ff]/.test(left)
        && !/[A-Za-z]/.test(left)
        && !/[\u0600-\u06ff]/.test(right)
        && !protectedRanges.some(([start, end]) => start < bilingualSeparator && end > 0)
      ) {
        const leading = value.match(/^\s*/)?.[0] ?? "";
        const trailing = value.match(/\s*$/)?.[0] ?? "";
        return `${leading}${right.trim()}${trailing}`;
      }
    }
    const replacements: Array<{ start: number; end: number; value: string }> = [];
    const overlaps = (start: number, end: number, ranges: Array<[number, number]>) =>
      ranges.some(([rangeStart, rangeEnd]) => start < rangeEnd && end > rangeStart);
    for (const [arabic, english] of printPrefixTranslations) {
      let position = value.indexOf(arabic);
      while (position >= 0) {
        const end = position + arabic.length;
        const before = value[position - 1] ?? "";
        const after = value[end] ?? "";
        const hasArabicBoundary = /[\u0600-\u06ff]/.test(before) || /[\u0600-\u06ff]/.test(after);
        const occupied = replacements.map(replacement => [replacement.start, replacement.end] as [number, number]);
        if (
          !hasArabicBoundary
          && !overlaps(position, end, protectedRanges)
          && !overlaps(position, end, occupied)
        ) {
          replacements.push({ start: position, end, value: english });
        }
        position = value.indexOf(arabic, position + arabic.length);
      }
    }
    if (!replacements.length) return value;
    replacements.sort((a, b) => a.start - b.start);
    let result = "";
    let cursor = 0;
    for (const replacement of replacements) {
      result += value.slice(cursor, replacement.start) + replacement.value;
      cursor = replacement.end;
    }
    return result + value.slice(cursor);
  };
  let current = walker.nextNode();
  while (current) {
    const text = current.nodeValue ?? "";
    const normalized = text.trim();
    const parent = current.parentElement;
    if (
      normalized
      && parent
      && !parent.closest("script,style,textarea,pre,code")
    ) {
      const isLabelText = !!parent.closest(
        "th,label,[class*='label'],[class*='lbl'],[class~='l'],[class~='k']",
      );
      const localizedRecordName = englishRecordNames.get(normalized.toLowerCase());
      if (localizedRecordName && !isLabelText) {
        const leading = text.match(/^\s*/)?.[0] ?? "";
        const trailing = text.match(/\s*$/)?.[0] ?? "";
        current.nodeValue = `${leading}${localizedRecordName}${trailing}`;
        current = walker.nextNode();
        continue;
      }
      if (protectedValues.has(normalized) && !isLabelText) {
        current = walker.nextNode();
        continue;
      }
      const exactTranslation = localizeUiTextForLanguage(text, language);
      current.nodeValue = exactTranslation === text
        ? translateStaticFragments(text)
        : exactTranslation;
    }
    current = walker.nextNode();
  }
  for (const element of Array.from(doc.querySelectorAll("[title],[alt],[aria-label],[placeholder]"))) {
    for (const attribute of ["title", "alt", "aria-label", "placeholder"]) {
      const value = element.getAttribute(attribute);
      if (value && !protectedValues.has(value.trim())) {
        element.setAttribute(attribute, localizeUiTextForLanguage(value, language));
      }
    }
  }

  const doctype = /^\s*<!doctype\b/i.test(html) ? "<!DOCTYPE html>" : "";
  return `${doctype}${doc.documentElement.outerHTML}`;
}

export function LocalizedText({ value }: { value: string }) {
  useTranslation();
  return localizeUiText(value);
}

export function localizeUiChildren(children: React.ReactNode): React.ReactNode {
  if (typeof children === "string") return localizeUiText(children);
  if (Array.isArray(children)) return children.map((child, index) =>
    <React.Fragment key={index}>{localizeUiChildren(child)}</React.Fragment>,
  );
  if (React.isValidElement<{ children?: React.ReactNode }>(children) && children.props.children != null) {
    return React.cloneElement(children, {
      ...children.props,
      children: localizeUiChildren(children.props.children),
    });
  }
  return children;
}
