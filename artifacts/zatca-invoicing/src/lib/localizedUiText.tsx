export function localizeUiText(value: string): string {
  if (!i18n.language?.startsWith("en")) return value;
  return localizeUiTextForLanguage(value, i18n.language);
}

export function localizeUiTextForLanguage(value: string, language: string): string {
  if (!language?.toLowerCase().startsWith("en")) return value;
  const trimmed = value.trim();
  const translated = translations.get(trimmed);
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

/**
 * Translate static labels in generated print HTML without rewriting record
 * values. Exact text values found in the source document data are protected.
 */
export function localizePrintHtml(html: string, language: string, documentData?: unknown): string {
  if (!language?.toLowerCase().startsWith("en") || typeof DOMParser === "undefined") return html;

  const protectedValues = new Set<string>();
  const visited = new WeakSet<object>();
  const collectValues = (value: unknown) => {
    if (typeof value === "string") {
      const normalized = value.trim();
      if (normalized) protectedValues.add(normalized);
      return;
    }
    if (typeof value === "number" && Number.isFinite(value)) {
      protectedValues.add(String(value));
      return;
    }
    if (!value || typeof value !== "object") return;
    if (visited.has(value)) return;
    visited.add(value);
    if (value instanceof Map) {
      for (const [key, item] of value) {
        collectValues(key);
        collectValues(item);
      }
      return;
    }
    if (value instanceof Set) {
      for (const item of value) collectValues(item);
      return;
    }
    for (const item of Object.values(value)) collectValues(item);
  };
  collectValues(documentData);

  const doc = new DOMParser().parseFromString(html, "text/html");
  doc.documentElement.lang = "en";
  doc.documentElement.dir = "ltr";
  for (const node of Array.from(doc.querySelectorAll('[dir="rtl"]'))) {
    node.setAttribute("dir", "ltr");
  }

  const walker = doc.createTreeWalker(doc.body, 4);
  let current = walker.nextNode();
  while (current) {
    const text = current.nodeValue ?? "";
    const normalized = text.trim();
    const parent = current.parentElement;
    if (
      normalized
      && parent
      && !parent.closest("script,style,textarea,pre,code")
      && !protectedValues.has(normalized)
    ) {
      let translated = localizeUiTextForLanguage(text, language);
      if (translated === text) {
        for (const [arabic, english] of translations) {
          if (!normalized.startsWith(arabic)) continue;
          const rest = normalized.slice(arabic.length);
          const delimiter = rest.match(/^\s*[:：|—-]\s*/)?.[0];
          if (!delimiter) continue;
          const suffix = rest.slice(delimiter.length).trim();
          if (!suffix || ![...protectedValues].some(value => suffix === value || suffix.startsWith(`${value} `))) continue;
          const leading = text.match(/^\s*/)?.[0] ?? "";
          const trailing = text.match(/\s*$/)?.[0] ?? "";
          translated = `${leading}${english}${delimiter}${suffix}${trailing}`;
          break;
        }
      }
      current.nodeValue = translated;
    }
    current = walker.nextNode();
  }
  for (const element of Array.from(doc.querySelectorAll("[title],[alt],[aria-label],[placeholder]"))) {
    for (const attribute of ["title", "alt", "aria-label", "placeholder"]) {
      const value = element.getAttribute(attribute);
      if (value && !protectedValues.has(value.trim())) {
        element.setAttribute(attribute, localizeUiTextForLanguage(value, language));
      }
    }
  }

  const doctype = /^\s*<!doctype\b/i.test(html) ? "<!DOCTYPE html>" : "";
  return `${doctype}${doc.documentElement.outerHTML}`;
}

export function LocalizedText({ value }: { value: string }) {
  useTranslation();
  return localizeUiText(value);
}

export function localizeUiChildren(children: React.ReactNode): React.ReactNode {
  if (typeof children === "string") return localizeUiText(children);
  if (Array.isArray(children)) return children.map((child, index) =>
    <React.Fragment key={index}>{localizeUiChildren(child)}</React.Fragment>,
  );
  if (React.isValidElement<{ children?: React.ReactNode }>(children) && children.props.children != null) {
    return React.cloneElement(children, {
      ...children.props,
      children: localizeUiChildren(children.props.children),
    });
  }
  return children;
}
