const suffix = randomBytes(5).toString("hex");
const serialTable = `sequence_restore_${suffix}`;
const emptyTable = `sequence_empty_${suffix}`;
const excludedTable = `sequence_excluded_${suffix}`;
const quotedTable = `sequence "quoted" ${suffix}`;
const raceTable = `sequence_race_${suffix}`;
const created = [serialTable, emptyTable, excludedTable, quotedTable, raceTable];
const qid = quotePostgresIdentifier;
const here = dirname(fileURLToPath(import.meta.url));

function rows(result: unknown): Record<string, unknown>[] {
  return (result as { rows?: Record<string, unknown>[] }).rows ?? [];
}

after(async () => {
  for (const table of created) {
    await db.execute(sql.raw(`DROP TABLE IF EXISTS ${qid(table)} CASCADE`)).catch(() => {});
  }
  await pool.end().catch(() => {});
});

test("reconciles restored serial/identity tables without lowering or touching empty/unlisted tables", async () => {
  await db.execute(sql.raw(`CREATE TABLE ${qid(serialTable)} (id SERIAL PRIMARY KEY)`));
  await db.execute(sql.raw(`CREATE TABLE ${qid(emptyTable)} (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`));
  await db.execute(sql.raw(`CREATE TABLE ${qid(excludedTable)} (id SERIAL PRIMARY KEY)`));
  await db.execute(sql.raw(`CREATE TABLE ${qid(quotedTable)} ("odd""id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`));

  await db.execute(sql.raw(`INSERT INTO ${qid(serialTable)} (id) VALUES (40)`));
  await db.execute(sql.raw(`INSERT INTO ${qid(excludedTable)} (id) VALUES (60)`));
  await db.execute(sql.raw(`INSERT INTO ${qid(quotedTable)} ("odd""id") VALUES (70)`));

  const first = await db.transaction((tx) => reconcilePostgresSequences(tx, {
    tables: [serialTable, emptyTable, quotedTable],
  }));
  assert.equal(first.inspected, 3);
  assert.equal(first.advanced, 2);

  const serialInserted = rows(await db.execute(sql.raw(
    `INSERT INTO ${qid(serialTable)} DEFAULT VALUES RETURNING id`,
  )))[0];
  const quotedInserted = rows(await db.execute(sql.raw(
    `INSERT INTO ${qid(quotedTable)} DEFAULT VALUES RETURNING "odd""id"`,
  )))[0];
  const emptyInserted = rows(await db.execute(sql.raw(
    `INSERT INTO ${qid(emptyTable)} DEFAULT VALUES RETURNING id`,
  )))[0];
  assert.equal(Number(serialInserted.id), 41);
  assert.equal(Number(quotedInserted['odd"id']), 71);
  assert.equal(Number(emptyInserted.id), 1, "an empty identity table must retain its initial allocation");

  const serialSequence = String(rows(await db.execute(sql.raw(
    `SELECT pg_get_serial_sequence('${serialTable}', 'id') AS name`,
  )))[0].name);
  await db.execute(sql.raw(`SELECT setval('${serialSequence.replace(/'/g, "''")}', 500, true)`));
  const second = await db.transaction((tx) => reconcilePostgresSequences(tx, { tables: [serialTable] }));
  assert.equal(second.advanced, 0);
  const advanced = rows(await db.execute(sql.raw(
    `INSERT INTO ${qid(serialTable)} DEFAULT VALUES RETURNING id`,
  )))[0];
  assert.equal(Number(advanced.id), 501, "an advanced sequence must never be lowered");

  const excludedInserted = rows(await db.execute(sql.raw(
    `INSERT INTO ${qid(excludedTable)} DEFAULT VALUES RETURNING id`,
  )))[0];
  assert.equal(
    Number(excludedInserted.id),
    1,
    "tables outside the restore allow-list must not be reconciled",
  );
});

